"""A002 schema EDA — structural pass over the four schemas.

The schemas are the only REAL local information (descriptions carry real
instrument metadata since the 2026-08-19 kit update). This script extracts
the structure that bears on modelling and writes a markdown report to
docs/analysis/A002-outputs/structural-report.md.

Run: .venv/Scripts/python notebooks/a002_schema_eda.py
"""

import json
import math
import sys

sys.stdout.reconfigure(encoding="utf-8")
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "external" / "starter-kit" / "data"
OUT = ROOT / "docs" / "analysis" / "A002-outputs"
SCHEMAS = ["sample", "unicef", "world_bank", "unhcr"]

LIKERT_HINTS = ("agree", "satisfied", "likely", "important", "safe",
                "effective", "always", "often", "sometimes", "never")
YESNO = ({"Yes", "No"}, {"Yes", "No", "Don't know"},
         {"Yes", "No", "I don't know"}, {"Yes", "No", "Refused"})


def load(name):
    with open(DATA / f"{name}.json", encoding="utf-8") as f:
        return json.load(f)


def item_type(values):
    """Heuristic taxonomy from the option list alone."""
    vset = set(values)
    lowered = [v.lower() for v in values]
    if any(vset == y or vset == y | {"Prefer not to answer"} for y in YESNO):
        return "binary(+DK/Ref)"
    if len(values) == 2:
        return "binary"
    if all(v.replace(".", "").replace("-", "").isdigit() for v in values):
        return "numeric-coded"
    if any(any(h in v for h in LIKERT_HINTS) for v in lowered):
        return "likert-like"
    if len(values) >= 8:
        return "categorical-wide"
    return "categorical"


def gate_stats(items):
    """Gate network topology: parent classes, fan-out, chain depth."""
    gated = {n: r["gate"] for n, r in items.items() if r.get("gate")}
    parents = Counter()
    fanout = Counter()
    for child, g in gated.items():
        p = g["parent"]
        parents[items[p]["class"]] += 1
        fanout[p] += 1

    depth = {}
    def d(name):
        if name in depth:
            return depth[name]
        g = items[name].get("gate")
        depth[name] = 0 if not g else 1 + d(g["parent"])
        return depth[name]
    for n in items:
        d(n)
    chain = Counter(depth[n] for n in gated)
    return gated, parents, fanout, chain


def main():
    OUT.mkdir(exist_ok=True)
    lines = ["# A002 structural report (generated by notebooks/a002_schema_eda.py)", ""]

    for name in SCHEMAS:
        schema = load(name)
        items = schema["items"]
        lines.append(f"## {name}")
        lines.append("")
        desc = schema.get("dataset", {}).get("description", "")
        lines.append(f"dataset.description: {desc}")
        lines.append(f"split: {schema.get('split')}")
        lines.append("")

        # class counts
        classes = Counter(r["class"] for r in items.values())
        lines.append(f"classes: {dict(classes)}  (total {len(items)})")

        # scored items = PREDICT; U over scored items, K incl sentinel
        scored = {n: r for n, r in items.items() if r["class"] == "PREDICT"}
        ks = {n: len(r["values"]) + (1 if r.get("gate") else 0)
              for n, r in scored.items()}
        u = sum(math.log(k) for k in ks.values()) / len(ks)
        lines.append(f"scored items: {len(scored)} · U = {u:.4f} · "
                     f"K range {min(ks.values())}–{max(ks.values())}")
        kdist = Counter(ks.values())
        lines.append(f"K distribution (K: n_items): "
                     f"{dict(sorted(kdist.items()))}")

        # highest-leverage items: largest log K (max headroom per cell)
        top = sorted(ks.items(), key=lambda t: -t[1])[:8]
        lines.append("largest-K scored items (max per-cell headroom): " +
                     ", ".join(f"{n} (K={k})" for n, k in top))
        lines.append("")

        # taxonomy
        tax = Counter(item_type(r["values"]) for r in scored.values())
        lines.append(f"scored-item taxonomy (heuristic): {dict(tax.most_common())}")
        lines.append("")

        # gate network
        gated, parents, fanout, chain = gate_stats(items)
        gated_scored = [n for n in gated if items[n]["class"] == "PREDICT"]
        lines.append(f"gates: {len(gated)} total, {len(gated_scored)} on scored items")
        lines.append(f"gate-parent classes: {dict(parents)}")
        lines.append(f"chain depth of gated items (depth: n): {dict(sorted(chain.items()))}")
        big_fan = sorted(fanout.items(), key=lambda t: -t[1])[:6]
        lines.append("largest fan-out parents: " +
                     ", ".join(f"{p} ({items[p]['class']}, {c} children)"
                               for p, c in big_fan))
        lines.append("")

        # stratum candidates: GIVEN items with low cardinality
        given = {n: r for n, r in items.items() if r["class"] == "GIVEN"}
        lines.append(f"GIVEN items ({len(given)}):")
        for n, r in sorted(given.items(), key=lambda t: len(t[1]["values"])):
            vals = r["values"]
            shown = vals if len(vals) <= 12 else vals[:12] + ["..."]
            lines.append(f"  - {n} (card {len(vals)}): {shown}  |  q: {r['question'][:90]}")
        lines.append("")

    report = "\n".join(lines)
    (OUT / "structural-report.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
