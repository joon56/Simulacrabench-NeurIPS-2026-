"""Render docs/tree.md (mermaid) from docs/experiments/E*.md headers.

Each experiment file starts with:
    # E00X — title
    parent: E00Y | —
    status: adopted | rejected | parked | superseded-by:E0ZZ

Usage: python scripts/render_tree.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "docs" / "experiments"
OUT = ROOT / "docs" / "tree.md"

STYLE = {
    "adopted": "fill:#d4edda,stroke:#28a745",
    "rejected": "fill:#f8d7da,stroke:#dc3545",
    "parked": "fill:#fff3cd,stroke:#ffc107",
    "superseded": "fill:#e2e3e5,stroke:#6c757d",
}


def parse(path):
    head = path.read_text(encoding="utf-8").splitlines()[:6]
    title = re.match(r"#\s+(E\d+)\s+—\s+(.*)", head[0])
    fields = dict(re.match(r"(\w[\w-]*):\s*(\S+)", line).groups()
                  for line in head[1:4] if re.match(r"\w[\w-]*:", line))
    return {
        "id": title.group(1),
        "title": title.group(2).strip(),
        "parent": fields.get("parent", "—"),
        "status": fields.get("status", "parked").split(":")[0]
                  .replace("superseded-by", "superseded"),
        "date": fields.get("date", ""),
    }


def main():
    nodes = [parse(p) for p in sorted(EXP.glob("E*.md"))]
    lines = [
        "# Experiment tree",
        "",
        "Generated by `python scripts/render_tree.py` from"
        " `docs/experiments/E*.md` — do not edit by hand.",
        "",
        "```mermaid",
        "flowchart TD",
    ]
    for n in nodes:
        label = f'{n["id"]}["{n["id"]} {n["title"]}<br/><i>{n["status"]} · {n["date"]}</i>"]'
        lines.append(f"    {label}")
        if n["parent"] != "—":
            lines.append(f'    {n["parent"]} --> {n["id"]}')
    for status, style in STYLE.items():
        ids = [n["id"] for n in nodes if n["status"] == status]
        if ids:
            lines.append(f"    classDef {status} {style}")
            lines.append(f'    class {",".join(ids)} {status}')
    lines += ["```", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(nodes)} experiments)")


if __name__ == "__main__":
    main()
